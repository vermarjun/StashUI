// Compiles per-component preview tuning into src/__registry__/previews.gen.ts.
//
// Sources (both per-component, so parallel agents never edit a shared file):
//   registry/<lib>/<name>.preview.json   — framing config (sidecar, optional)
//   public/previews/<name>.webm           — looped grid clip (sets hasVideo)
//
// Run: node scripts/build-previews.mjs   (also invoked by `npm run previews`)

import {
  readdirSync,
  readFileSync,
  writeFileSync,
  existsSync,
  statSync,
} from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const registryDir = join(root, "registry");
const videoDir = join(root, "public", "previews");
const outFile = join(root, "src", "__registry__", "previews.gen.ts");

const DEVICES = new Set(["mobile", "tablet", "desktop"]);
const ALIGNS = new Set(["center", "top"]);
const BACKGROUNDS = new Set(["none", "dots", "grid", "checker"]);

const DEFAULTS = {
  device: "desktop",
  height: 600,
  align: "center",
  scroll: false,
  background: "none",
};

/** Recursively collect *.preview.json sidecars under registry/. */
function findSidecars(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...findSidecars(full));
    else if (entry.name.endsWith(".preview.json")) out.push(full);
  }
  return out;
}

/** name -> client-safe PreviewConfig (without hasVideo, which we add below). */
const configs = {};

for (const file of findSidecars(registryDir)) {
  const name = file.split("/").pop().replace(/\.preview\.json$/, "");
  let raw;
  try {
    raw = JSON.parse(readFileSync(file, "utf8"));
  } catch (err) {
    console.warn(`! Skipping invalid sidecar ${file}: ${err.message}`);
    continue;
  }
  const device = DEVICES.has(raw.device) ? raw.device : DEFAULTS.device;
  const align = ALIGNS.has(raw.align) ? raw.align : DEFAULTS.align;
  const background = BACKGROUNDS.has(raw.background)
    ? raw.background
    : DEFAULTS.background;
  const height =
    Number.isFinite(raw.height) && raw.height > 0
      ? Math.round(raw.height)
      : DEFAULTS.height;
  const scroll = raw.scroll === true;
  configs[name] = { device, height, align, scroll, background };
}

/** Which components have a captured grid clip. */
const hasVideo = {};
if (existsSync(videoDir)) {
  for (const f of readdirSync(videoDir)) {
    if (f.endsWith(".webm")) hasVideo[f.replace(/\.webm$/, "")] = true;
  }
}

// Union of names that have either a sidecar or a video; the rest fall back to
// DEFAULT_PREVIEW at runtime (no need to emit an entry).
const names = [
  ...new Set([...Object.keys(configs), ...Object.keys(hasVideo)]),
].sort();

const entries = {};
for (const name of names) {
  entries[name] = { ...DEFAULTS, ...(configs[name] ?? {}), hasVideo: !!hasVideo[name] };
}

const banner = `// AUTO-GENERATED by scripts/build-previews.mjs — do not edit by hand.
//
// Per-component preview tuning. Each component is framed individually:
//   device     — default viewport for the detail page (the box acts as the screen)
//   height     — detail-page box height in px
//   align      — center a self-contained widget, or top-align a page/hero
//   scroll     — allow vertical scroll inside the box (multi-screen heroes/pages)
//   background — backdrop behind the component in the box
//   hasVideo   — a looped grid clip exists at /previews/<name>.{webm,mp4}
`;

const file = `${banner}
export type PreviewDevice = "mobile" | "tablet" | "desktop";
export type PreviewAlign = "center" | "top";
export type PreviewBackground = "none" | "dots" | "grid" | "checker";

export interface PreviewConfig {
  device: PreviewDevice;
  height: number;
  align: PreviewAlign;
  scroll: boolean;
  background: PreviewBackground;
  hasVideo: boolean;
}

/** Nominal device widths (the detail page caps "desktop" to its container). */
export const DEVICE_WIDTHS: Record<PreviewDevice, number> = {
  mobile: 390,
  tablet: 834,
  desktop: 1280,
};

export const DEFAULT_PREVIEW: PreviewConfig = {
  device: "desktop",
  height: 600,
  align: "center",
  scroll: false,
  background: "none",
  hasVideo: false,
};

export const previews: Record<string, PreviewConfig> = ${JSON.stringify(entries, null, 2)};

export function getPreview(name: string): PreviewConfig {
  return previews[name] ?? DEFAULT_PREVIEW;
}
`;

writeFileSync(outFile, file);
const videoCount = Object.values(entries).filter((e) => e.hasVideo).length;
console.log(
  `✓ previews.gen.ts: ${names.length} tuned (${videoCount} with video).`,
);
