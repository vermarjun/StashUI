const GLYPH = Object.fromEntries(Object.entries(G).map(([c, s]) => [c, s.split(" ").map((r) => parseInt(r, 2))]));

export const textWidth = (s, scale) => s.length * 6 * scale - scale;

/** Draw `s` (upper-cased; unknown characters become spaces) at x,y into an RGB buffer. */
export function drawText(buf, W, H, s, x, y, scale, [r, g, b]) {
  for (const ch of s.toUpperCase()) {
    const rows = GLYPH[ch] || GLYPH[" "];
    for (let gy = 0; gy < 7; gy++)
      for (let gx = 0; gx < 5; gx++)
        if (rows[gy] & (16 >> gx))
          for (let dy = 0; dy < scale; dy++)
            for (let dx = 0; dx < scale; dx++) {
              const px = x + gx * scale + dx, py = y + gy * scale + dy;
              if (px < 0 || py < 0 || px >= W || py >= H) continue;
              const o = (py * W + px) * 3;
              buf[o] = r; buf[o + 1] = g; buf[o + 2] = b;
            }
    x += 6 * scale;
  }
}

export function fillRect(buf, W, H, x, y, w, h, [r, g, b]) {
  for (let py = Math.max(0, y); py < Math.min(H, y + h); py++)
    for (let px = Math.max(0, x); px < Math.min(W, x + w); px++) {
      const o = (py * W + px) * 3;
      buf[o] = r; buf[o + 1] = g; buf[o + 2] = b;
    }
}
